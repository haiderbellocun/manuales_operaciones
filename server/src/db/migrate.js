export async function migrate() {
  await prepareExistingDatabaseForSchema();

  const schemaPath = path.join(__dirname, '..', '..', 'sql', 'schema.sql');
  const sql = fs.readFileSync(schemaPath, 'utf8');
  await query(sql);

  await renameColumn('areas', 'code', 'abbreviation');
  await renameColumn('document_types', 'short', 'abbreviation');
  await renameColumn('documents', 'code', 'document_number');

  await dropColumn('areas', 'code');
  await dropColumn('document_types', 'short');
  await dropColumn('documents', 'code');
  await dropColumn('document_types', 'key');
  await dropColumn('roles', 'key');
  await dropColumn('people', 'key');
  await dropColumn('users', 'password');
  await dropColumn('users', 'legacy_key');
  await dropColumn('documents', 'legacy_key');
  await dropColumn('workflow_items', 'legacy_key');
  await dropColumn('update_requests', 'legacy_key');

  await addColumn('workflow_items', 'assignee_user_id', 'INTEGER REFERENCES users(id)');
  await addColumn('workflow_items', 'reviewer_user_id', 'INTEGER REFERENCES users(id)');
  await addColumn('workflow_items', 'approver_user_id', 'INTEGER REFERENCES users(id)');
  await addColumn('workflow_items', 'completed_at', 'TIMESTAMPTZ');
  await addColumn('workflow_items', 'completed_by', 'INTEGER REFERENCES users(id)');
  await addColumn('workflow_items', 'reviewed_at', 'TIMESTAMPTZ');
  await addColumn('workflow_items', 'reviewed_by', 'INTEGER REFERENCES users(id)');
  await addColumn('workflow_items', 'decision', 'VARCHAR(30)');
  await addColumn('workflow_items', 'comments', 'TEXT');
  await addColumn('users', 'profile_picture_url', 'TEXT');
  await addColumn('activity_log', 'event_type', "VARCHAR(50) NOT NULL DEFAULT 'general'");
  await addColumn('activity_log', 'details', "JSONB NOT NULL DEFAULT '{}'");
  await addColumn('activity_log', 'created_at', 'TIMESTAMPTZ NOT NULL DEFAULT NOW()');
  await addColumn('documents', 'downloads', 'INTEGER NOT NULL DEFAULT 0');
  await addColumn('documents', 'last_viewed_at', 'TIMESTAMPTZ');
  await addColumn('documents', 'last_downloaded_at', 'TIMESTAMPTZ');
  await addColumn('documents', 'published_at', 'TIMESTAMPTZ');
  await addColumn('documents', 'visible_to_all', 'BOOLEAN NOT NULL DEFAULT false');

  await query(`
    UPDATE documents d
    SET published_at = COALESCE(
      (
        SELECT wi.completed_at
        FROM workflow_items wi
        WHERE wi.doc_id = d.id
          AND wi.decision = 'published'
          AND wi.completed_at IS NOT NULL
        ORDER BY wi.completed_at DESC
        LIMIT 1
      ),
      (
        SELECT al.created_at
        FROM activity_log al
        WHERE al.doc_id = d.id
          AND (
            al.details->>'status' = 'published'
            OR al.details->>'action' = 'publish'
          )
        ORDER BY al.created_at DESC
        LIMIT 1
      ),
      CASE
        WHEN d.state IN ('publicado', 'vencido', 'archivado')
          THEN COALESCE(d.updated::timestamptz, d.created::timestamptz)
        ELSE NULL
      END
    )
    WHERE d.published_at IS NULL
      AND d.state IN ('publicado', 'vencido', 'archivado')
  `);

  await addColumn('areas', 'requires_coordination', 'BOOLEAN NOT NULL DEFAULT false');

  await query(`
    CREATE TABLE IF NOT EXISTS coordinations (
      id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      area_id      INTEGER NOT NULL REFERENCES areas(id) ON DELETE CASCADE,
      name         VARCHAR(200) NOT NULL,
      abbreviation VARCHAR(10)  NOT NULL,
      sort_order   INTEGER NOT NULL DEFAULT 0,
      UNIQUE (area_id, abbreviation)
    )
  `);
  await query('CREATE INDEX IF NOT EXISTS idx_coordinations_area ON coordinations(area_id)');

  await addColumn('documents', 'coordination_id', 'INTEGER REFERENCES coordinations(id) ON DELETE SET NULL');
  await addColumn('users', 'coordination_id', 'INTEGER REFERENCES coordinations(id) ON DELETE SET NULL');
  await addColumn('people', 'coordination_id', 'INTEGER REFERENCES coordinations(id) ON DELETE SET NULL');
  await query('CREATE INDEX IF NOT EXISTS idx_documents_coordination ON documents(coordination_id)');

  await query(`
    WITH interaction_totals AS (
      SELECT
        doc_id,
        COUNT(*) FILTER (WHERE interaction_type = 'view')::int AS views,
        COUNT(*) FILTER (WHERE interaction_type = 'download')::int AS downloads,
        MAX(occurred_at) FILTER (WHERE interaction_type = 'view') AS last_viewed_at,
        MAX(occurred_at) FILTER (WHERE interaction_type = 'download') AS last_downloaded_at
      FROM document_interactions
      GROUP BY doc_id
    )
    UPDATE documents d
    SET views = GREATEST(d.views, totals.views),
        downloads = GREATEST(d.downloads, totals.downloads),
        last_viewed_at = COALESCE(
          GREATEST(d.last_viewed_at, totals.last_viewed_at),
          d.last_viewed_at,
          totals.last_viewed_at
        ),
        last_downloaded_at = COALESCE(
          GREATEST(d.last_downloaded_at, totals.last_downloaded_at),
          d.last_downloaded_at,
          totals.last_downloaded_at
        )
    FROM interaction_totals totals
    WHERE totals.doc_id = d.id
  `);

  await refreshAreaCatalog();

  await query(`
    INSERT INTO document_versions (
      doc_id, version, original_name, stored_name, mime_type, file_size, created_at, created_by, note
    )
    SELECT d.id, d.version, f.original_name, f.stored_name, f.mime_type, f.file_size,
           COALESCE(f.uploaded_at, NOW()), f.uploaded_by, 'Version vigente antes de activar versionamiento'
    FROM documents d
    JOIN document_files f ON f.doc_id = d.id
    ON CONFLICT (doc_id, version) DO NOTHING
  `);

  await query(`
    UPDATE workflow_items wi
    SET assignee_user_id = u.id
    FROM users u
    WHERE wi.assignee_user_id IS NULL
      AND LOWER(wi.assignee) = LOWER(u.name)
  `);

  await query(`
    UPDATE workflow_items
    SET reviewer_user_id = COALESCE(
      reviewer_user_id,
      CASE
        WHEN stage = 'revision' THEN assignee_user_id
        WHEN reviewed_by IS NOT NULL THEN reviewed_by
        ELSE NULL
      END
    )
    WHERE reviewer_user_id IS NULL
  `);

  await query(`
    UPDATE workflow_items wi
    SET reviewer_user_id = (
      SELECT u.id
      FROM users u
      JOIN documents d ON d.id = wi.doc_id
      WHERE u.role_id IN (2, 4, 8)
        AND u.status = 'Activo'
        AND u.area_id = d.area_id
      ORDER BY
        CASE u.role_id
          WHEN 4 THEN 0
          WHEN 2 THEN 1
          ELSE 2
        END,
        u.id
      LIMIT 1
    )
    WHERE wi.completed_at IS NULL
      AND NOT EXISTS (
      SELECT 1
      FROM users current_reviewer
      JOIN documents current_document ON current_document.id = wi.doc_id
      WHERE current_reviewer.id = wi.reviewer_user_id
        AND current_reviewer.role_id IN (2, 4, 8)
        AND current_reviewer.status = 'Activo'
        AND current_reviewer.area_id = current_document.area_id
    )
  `);

  await query(`
    UPDATE workflow_items wi
    SET approver_user_id = (
      SELECT u.id
      FROM users u
      JOIN documents d ON d.id = wi.doc_id
      WHERE u.role_id IN (2, 5, 8)
        AND u.status = 'Activo'
        AND u.area_id = d.area_id
      ORDER BY
        CASE u.role_id
          WHEN 5 THEN 0
          WHEN 2 THEN 1
          ELSE 2
        END,
        u.id
      LIMIT 1
    )
    WHERE wi.completed_at IS NULL
      AND NOT EXISTS (
      SELECT 1
      FROM users current_approver
      JOIN documents current_document ON current_document.id = wi.doc_id
      WHERE current_approver.id = wi.approver_user_id
        AND current_approver.role_id IN (2, 5, 8)
        AND current_approver.status = 'Activo'
        AND current_approver.area_id = current_document.area_id
    )
  `);

  await query(`
    UPDATE workflow_items wi
    SET assignee_user_id = wi.reviewer_user_id,
        assignee = COALESCE(
          (SELECT reviewer.name FROM users reviewer WHERE reviewer.id = wi.reviewer_user_id),
          'Revisor del area pendiente'
        )
    WHERE wi.stage = 'revision'
      AND wi.completed_at IS NULL
  `);

  await query(`
    UPDATE workflow_items wi
    SET assignee_user_id = wi.approver_user_id,
        assignee = COALESCE(
          (SELECT approver.name FROM users approver WHERE approver.id = wi.approver_user_id),
          'Aprobador del area pendiente'
        )
    WHERE wi.stage = 'aprobacion'
      AND wi.completed_at IS NULL
  `);

  await query(`
    UPDATE roles
    SET perms = jsonb_set(perms, '{administrar}', to_jsonb(id = 1), true)
    WHERE NOT (perms ? 'administrar')
  `);
}
