import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { query } from './pool.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));

async function columnExists(table, column) {
  const { rows } = await query(`
    SELECT 1
    FROM information_schema.columns
    WHERE table_schema = 'public'
      AND table_name = $1
      AND column_name = $2
    LIMIT 1
  `, [table, column]);
  return rows.length > 0;
}

async function tableExists(table) {
  const { rows } = await query(`
    SELECT 1
    FROM information_schema.tables
    WHERE table_schema = 'public'
      AND table_name = $1
    LIMIT 1
  `, [table]);
  return rows.length > 0;
}

async function renameColumn(table, from, to) {
  if ((await columnExists(table, from)) && !(await columnExists(table, to))) {
    await query(`ALTER TABLE ${table} RENAME COLUMN ${from} TO ${to}`);
  }
}

async function dropColumn(table, column) {
  if (await columnExists(table, column)) {
    await query(`ALTER TABLE ${table} DROP COLUMN ${column}`);
  }
}

async function addColumn(table, column, definition) {
  if (!(await columnExists(table, column))) {
    await query(`ALTER TABLE ${table} ADD COLUMN ${column} ${definition}`);
  }
}

async function prepareExistingDatabaseForSchema() {
  if (await tableExists('areas')) {
    await addColumn('areas', 'requires_coordination', 'BOOLEAN NOT NULL DEFAULT false');
  }

  if (await tableExists('areas') && !(await tableExists('coordinations'))) {
    await query(`
      CREATE TABLE IF NOT EXISTS coordinations (
        id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        area_id      INTEGER NOT NULL REFERENCES areas(id) ON DELETE CASCADE,
        name         VARCHAR(200) NOT NULL,
        abbreviation VARCHAR(10)  NOT NULL,
        sort_order   INTEGER NOT NULL DEFAULT 0,
        UNIQUE (area_id, abbreviation)
      )
    `);
  }

  if (await tableExists('documents')) {
    await addColumn('documents', 'coordination_id', 'INTEGER REFERENCES coordinations(id) ON DELETE SET NULL');
  }
  if (await tableExists('users')) {
    await addColumn('users', 'coordination_id', 'INTEGER REFERENCES coordinations(id) ON DELETE SET NULL');
    await addColumn('users', 'profile_picture_url', 'TEXT');
  }
  if (await tableExists('people')) {
    await addColumn('people', 'coordination_id', 'INTEGER REFERENCES coordinations(id) ON DELETE SET NULL');
  }
}

